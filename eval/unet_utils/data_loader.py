"""
Dataset classes for the MVTec **classification** evaluation task.

Adapted from O2MAG `eval/unet_utils/data_loader.py`, trimmed to classification
only (the U-Net anomaly-detection classes and the `cv2`/`imgaug` imports are
dropped — `imgaug` is not installed in this repo and is unused for classification).

Layout this code expects
-------------------------
Both datasets read the *MVTec* layout ``<root>/<object>/test/<defect_type>/<img>``:

* **Train** (synthetic defects produced by ``eval/generate_defects.py``):
    ``<generated_data_path>/<object>/test/<defect_type>/<i>.png``
* **Test** (real MVTec):
    ``<mvtec_path>/<object>/test/<defect_type>/<img>.png``

     The defect types (class labels) are discovered from the *generated* train
     folder, so the classifier is trained/evaluated over exactly the defect types
     the ip2p model was asked to produce. There is no "good/normal" class here.

Localization datasets
---------------------
The localization (DRAEM-style) training set mixes:

* **synthetic anomalies** from ``<generated_data_path>/<object>/test/<defect>/<i>``
  with their **stored** pseudo-GT masks
  ``<generated_data_path>/<object>/ground_truth/<defect>/<i>_mask.png``
  (the Otsu diff masks written by ``eval/generate_defects.py`` — reused as-is,
  NOT recomputed), and
* **real normal images** from ``<mvtec_path>/<object>/train/good/`` as the
  ``good`` class (ip2p only generates defects, so there are no synthetic goods).

Normal masks are all-zeros. The eval set reads the real MVTec ``test`` +
``ground_truth`` folders exactly as O2MAG's ``MVTecDRAEMTestDataset_partial`` does,
but without `cv2`/`imgaug` (not installed here).
     """

import json
import os
import random

import torch
from PIL import Image
from torch.utils.data import Dataset
from torchvision import transforms

IMAGE_EXTS = (".png", ".jpg", ".jpeg")


def _sorted_image_files(folder):
    """Return image filenames in ``folder`` sorted by their numeric prefix."""
    if not os.path.isdir(folder):
        return []
    files = [
        f
        for f in os.listdir(folder)
        if f.lower().endswith(IMAGE_EXTS) and os.path.isfile(os.path.join(folder, f))
    ]
    # Sort by the leading digits of the basename (e.g. "000.png" -> 0).
    files.sort(
        key=lambda x: int(
            "".join(c for c in os.path.splitext(x)[0] if c.isdigit()) or 0
        )
    )
    return files


class MVTec_classification_train(Dataset):
    """Training set: synthetic defect images generated by the ip2p model.

    Reads from ``<generated_data_path>/<object>/test/<defect_type>/<img>``.
    Defect subdirectories become the class labels (in sorted order).
    """

    def __init__(self, args, sample_name):
        self.root_dir = os.path.join(args.generated_data_path, sample_name, "test")
        self.anomaly_names = [
            d
            for d in os.listdir(self.root_dir)
            if os.path.isdir(os.path.join(self.root_dir, d))
        ]
        # Optional CLIP filtering: if --clip_bad_json is given, skip indices
        # listed as bad for this object/defect in that JSON.
        clip_bad = {}
        clip_path = getattr(args, "clip_bad_json", None)
        if clip_path and os.path.isfile(clip_path):
            with open(clip_path, "r") as f:
                clip_bad = json.load(f)

        self.img_paths = []
        self.labels = []
        for idx, anomaly in enumerate(self.anomaly_names):
            defect_dir = os.path.join(self.root_dir, anomaly)
            bad_set = set(clip_bad.get(f"{sample_name}/{anomaly}", []))
            for fname in _sorted_image_files(defect_dir):
                base = os.path.splitext(fname)[0]
                if base in bad_set:
                    continue
                self.img_paths.append(os.path.join(defect_dir, fname))
                self.labels.append(idx)

        self.loader = transforms.Compose(
            [
                transforms.ToTensor(),
                transforms.Resize([256, 256]),
            ]
        )
        self.length = len(self.img_paths)

    def __len__(self):
        return self.length 

    def class_num(self):
        return len(self.anomaly_names)

    def return_anomaly_names(self):
        return self.anomaly_names

    def __getitem__(self, idx):
        image = self.loader(
            Image.open(self.img_paths[idx % len(self.img_paths)]).convert("RGB")
        )
        label = self.labels[idx % len(self.img_paths)]
        return image, label


class MVTec_classification_test(Dataset):
    """Test set: real MVTec test images."""

    def __init__(self, args, sample_name, anomaly_names):
        root_dir = os.path.join(args.mvtec_path, sample_name, "test")
        self.anomaly_names = anomaly_names
        self.img_paths = []
        self.labels = []
        for idx, anomaly_name in enumerate(self.anomaly_names):
            img_path = os.path.join(root_dir, anomaly_name)
            files = _sorted_image_files(img_path)
            for fname in files:
                self.img_paths.append(os.path.join(img_path, fname))
                self.labels.append(idx)

        self.loader = transforms.Compose(
            [
                transforms.ToTensor(),
                transforms.Resize([256, 256]),
            ]
        )
        self.length = len(self.img_paths)

    def __len__(self):
        return self.length

    def class_num(self):
        return len(self.anomaly_names)

    def __getitem__(self, idx):
        image = self.loader(
            Image.open(self.img_paths[idx % len(self.img_paths)]).convert("RGB")
        )
        label = self.labels[idx % len(self.img_paths)]
        return image, label


