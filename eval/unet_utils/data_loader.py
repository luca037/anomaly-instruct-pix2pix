# Anomaly-localization (DRAEM-style) datasets
# ---------------------------------------------------------------------------

LOCALIZE_SIZE = 256


class RandomAugmentation:
    """Random crop/rotate/translate, copied from O2MAG (applied to anomaly pairs)."""

    def __init__(self, prob=0.5):
        self.prob = prob

    def __call__(self, image, mask):
        if random.random() < self.prob:
            width, height = image.size

            crop_x = random.randint(0, width // 16)
            crop_y = random.randint(0, height // 16)
            image = image.crop((crop_x, crop_y, width - crop_x, height - crop_y))
            mask = mask.crop((crop_x, crop_y, width - crop_x, height - crop_y))

            angle = random.uniform(-30, 30)
            image = image.rotate(angle, expand=True)
            mask = mask.rotate(angle, expand=True)

            dx = random.randint(-16, 16)
            dy = random.randint(-16, 16)
            translated_image = Image.new("RGB", (width, height), color="black")
            translated_mask = Image.new("L", (width, height), color=0)
            translated_image.paste(image, (dx, dy))
            translated_mask.paste(mask, (dx, dy))

            image, mask = translated_image, translated_mask

        return image, mask


class Real_RandomAugmentation(RandomAugmentation):
    """Identical augmentation used by O2MAG for the real-MVTec-anomaly branch."""


class AnomalyLocalizationTrainDataset(Dataset):
    """Training set for the anomaly-detection segmentor.

    Mirrors O2MAG's ``MVTec_Anomaly_Detection`` sampling, with these branches
    drawn per-sample by probability:
      * 50% real MVTec ``train/good`` images (all-zero mask, normal class);
      * 10% real MVTec *anomalies* (``<mvtec>/<obj>/test`` + ``ground_truth``);
      * 40% synthetic defects (``<generated>/<obj>/test`` + ``ground_truth``).
    Both anomaly branches receive the O2MAG random augmentation (crop/rotate/
    translate). ``length`` is the number of samples drawn per epoch (O2MAG uses
    500); since sampling is with replacement, the same physical images recur.
    """

    def __init__(self, args, sample_name, length=500):
        self.generated_root = os.path.join(args.generated_data_path, sample_name)
        self.test_root = os.path.join(self.generated_root, "test")
        self.gt_root = os.path.join(self.generated_root, "ground_truth")

        self.mvtec_root = os.path.join(args.mvtec_path, sample_name)
        self.mvtec_good_root = os.path.join(self.mvtec_root, "train", "good")
        self.mvtec_test_root = os.path.join(self.mvtec_root, "test")
        self.mvtec_gt_root = os.path.join(self.mvtec_root, "ground_truth")

        # Optional CLIP filtering for the synthetic branch.
        clip_bad = {}
        clip_path = getattr(args, "clip_bad_json", None)
        if clip_path and os.path.isfile(clip_path):
            with open(clip_path, "r") as f:
                clip_bad = json.load(f)

        # Generated (synthetic) defect folders -> (img_paths, mask_paths) per defect.
        self.gen_img_paths = []
        self.gen_mask_paths = []
        if os.path.isdir(self.test_root):
            for defect_type in sorted(os.listdir(self.test_root)):
                img_dir = os.path.join(self.test_root, defect_type)
                mask_dir = os.path.join(self.gt_root, defect_type)
                if not os.path.isdir(img_dir):
                    continue
                bad_set = set(clip_bad.get(f"{sample_name}/{defect_type}", []))
                imgs, masks = [], []
                for fname in _sorted_image_files(img_dir):
                    base = os.path.splitext(fname)[0]
                    if base in bad_set:
                        continue
                    mask_path = os.path.join(mask_dir, f"{base}_mask.png")
                    if not os.path.isfile(mask_path):
                        mask_path = os.path.join(img_dir, f"{base}_mask.png")
                    if not os.path.isfile(mask_path):
                        continue
                    imgs.append(os.path.join(img_dir, fname))
                    masks.append(mask_path)
                if imgs:
                    self.gen_img_paths.append(imgs)
                    self.gen_mask_paths.append(masks)

        # Real MVTec anomalies ("extra real anomaly" branch).
        self.extra_img_paths = []
        self.extra_mask_paths = []
        if os.path.isdir(self.mvtec_gt_root):
            for defect_type in sorted(os.listdir(self.mvtec_gt_root)):
                img_dir = os.path.join(self.mvtec_test_root, defect_type)
                mask_dir = os.path.join(self.mvtec_gt_root, defect_type)
                if not os.path.isdir(img_dir):
                    continue
                imgs, masks = [], []
                for fname in _sorted_image_files(img_dir):
                    base = os.path.splitext(fname)[0]
                    mask_path = os.path.join(mask_dir, f"{base}_mask.png")
                    if not os.path.isfile(mask_path):
                        continue
                    imgs.append(os.path.join(img_dir, fname))
                    masks.append(mask_path)
                if imgs:
                    self.extra_img_paths.append(imgs)
                    self.extra_mask_paths.append(masks)

        # Real MVTec good (normal) images.
        self.good_files = (
            [
                os.path.join(self.mvtec_good_root, f)
                for f in _sorted_image_files(self.mvtec_good_root)
            ]
            if os.path.isdir(self.mvtec_good_root)
            else []
        )

        self.augmentation = RandomAugmentation()
        self.real_augmentation = Real_RandomAugmentation()
        self.loader = transforms.Compose(
            [transforms.ToTensor(), transforms.Resize([LOCALIZE_SIZE, LOCALIZE_SIZE])]
        )
        self.mask_loader = transforms.Compose(
            [transforms.ToTensor(), transforms.Resize([LOCALIZE_SIZE, LOCALIZE_SIZE])]
        )
        self.length = length

    def __len__(self):
        return self.length

    def _load_gen(self, idx):
        anomaly_id = random.randint(0, len(self.gen_img_paths) - 1)
        n = len(self.gen_img_paths[anomaly_id])
        img_path = self.gen_img_paths[anomaly_id][idx % n]
        mask_path = self.gen_mask_paths[anomaly_id][idx % n]
        image = Image.open(img_path).convert("RGB")
        mask = Image.open(mask_path).convert("L")
        image, mask = self.augmentation(image, mask)
        image = self.loader(image)
        mask = self.mask_loader(mask)
        mask = (mask > 0.5).float()
        return image, mask

    def _load_extra(self, idx):
        anomaly_id = random.randint(0, len(self.extra_img_paths) - 1)
        n = len(self.extra_img_paths[anomaly_id])
        img_path = self.extra_img_paths[anomaly_id][idx % n]
        mask_path = self.extra_mask_paths[anomaly_id][idx % n]
        image = Image.open(img_path).convert("RGB")
        mask = Image.open(mask_path).convert("L")
        image, mask = self.real_augmentation(image, mask)
        image = self.loader(image)
        mask = self.mask_loader(mask)
        mask = (mask > 0.5).float()
        return image, mask

    def __getitem__(self, idx):
        # Probabilities match O2MAG: 0.5 good, 0.1 real anomaly, 0.4 generated.
        p = random.random()
        if p < 0.5:
            img_path = self.good_files[idx % len(self.good_files)]
            image = self.loader(Image.open(img_path).convert("RGB"))
            mask = torch.zeros(1, LOCALIZE_SIZE, LOCALIZE_SIZE, dtype=torch.float32)
            return image, mask
        elif p < 0.6:
            if self.extra_img_paths:
                return self._load_extra(idx)
            return self._load_gen(idx)
        else:
            if self.gen_img_paths:
                return self._load_gen(idx)
            return self._load_extra(idx)


class AnomalyLocalizationTestDataset(Dataset):
    """Eval set: real MVTec test images + their GT masks, grouped per defect type.

    Mirrors O2MAG's ``MVTecDRAEMTestDataset_partial`` but reads real GT masks and
    needs no ``cv2``/``imgaug``.
    """

    def __init__(self, args, sample_name, anomaly_names):
        self.root_dir = os.path.join(args.mvtec_path, sample_name)
        self.anomaly_names = anomaly_names
        self.samples = []  # (defect_type, img_path, mask_path)
        for defect_type in self.anomaly_names:
            img_dir = os.path.join(self.root_dir, "test", defect_type)
            mask_dir = os.path.join(self.root_dir, "ground_truth", defect_type)
            if not os.path.isdir(img_dir):
                continue
            for fname in _sorted_image_files(img_dir):
                img_path = os.path.join(img_dir, fname)
                base = os.path.splitext(fname)[0]
                mask_path = os.path.join(mask_dir, f"{base}_mask.png")
                self.samples.append(
                    (
                        defect_type,
                        img_path,
                        mask_path if os.path.isfile(mask_path) else None,
                    )
                )

        self.loader = transforms.Compose(
            [transforms.ToTensor(), transforms.Resize([LOCALIZE_SIZE, LOCALIZE_SIZE])]
        )
        self.mask_loader = transforms.Compose(
            [transforms.ToTensor(), transforms.Resize([LOCALIZE_SIZE, LOCALIZE_SIZE])]
        )
        self.length = len(self.samples)

    def __len__(self):
        return self.length

    def __getitem__(self, idx):
        defect_type, img_path, mask_path = self.samples[idx]
        image = self.loader(Image.open(img_path).convert("RGB"))
        if mask_path is None or not os.path.isfile(mask_path):
            mask = torch.zeros(1, LOCALIZE_SIZE, LOCALIZE_SIZE, dtype=torch.float32)
        else:
            mask = self.mask_loader(Image.open(mask_path).convert("L"))
            mask = (mask > 0.5).float()
        return image, mask, defect_type
